const header = `// Code generated by backend/cmd/dslgen from backend/pkg/dsl/schema.json. DO NOT EDIT.
// スキーマを変えたら backend/ で ` + "`make dsl-gen`" + ` を回してコミットする(古いと backend のテストが落ちる)。

package ` + kotlinPackage + `
`

// Generate returns the Kotlin files (file name → content) for the schema.
func Generate(schema []byte) (map[string]string, error) {
	g, err := newGenerator(schema)
	if err != nil {
		return nil, err
	}
	// Collect which lenient object serializers are needed before any file is rendered.
	for _, c := range g.classes {
		for _, p := range c.props {
			g.propLines(c, p)
		}
	}
	return map[string]string{
		"Models.kt":    g.renderModels(),
		"Component.kt": g.renderComponent(),
		"Enums.kt":     g.renderEnums(),
		"Expr.kt":      g.renderSealed(),
		"DslKeys.kt":   g.renderKeys(),
	}, nil
}

func imports(names ...string) string {
	var b strings.Builder
	b.WriteString("\n")
	for _, n := range names {
		b.WriteString("import " + n + "\n")
	}
	return b.String()
}

// ---- classes ---------------------------------------------------------------

func (g *generator) renderModels() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(imports(
		"kotlinx.serialization.Serializable",
		"kotlinx.serialization.json.JsonElement",
		"kotlinx.serialization.json.JsonObject",
	))
	// Render every class first so lenient serializers in use are known.
	var body strings.Builder
	for _, c := range g.classes {
		if c.name == componentName {
			continue
		}
		body.WriteString("\n")
		body.WriteString(g.renderClass(c, "@Serializable", nil))
	}
	b.WriteString(body.String())
	b.WriteString(g.renderLenientObjects(false))
	return b.String()
}

func (g *generator) renderClass(c *class, annotations string, extra []string) string {
	var b strings.Builder
	b.WriteString(annotations + "\n")
	if len(c.props) == 0 && len(extra) == 0 {
		fmt.Fprintf(&b, "class %s", c.name)
	} else {
		fmt.Fprintf(&b, "data class %s(\n", c.name)
		for _, p := range c.props {
			for _, line := range g.propLines(c, p) {
				b.WriteString("    " + line + "\n")
			}
		}
		for _, line := range extra {
			b.WriteString("    " + line + "\n")
		}
		b.WriteString(")")
	}
	if c.implement != "" {
		b.WriteString(" : " + c.implement)
	}
	b.WriteString(" {\n    companion object\n}\n")
	return b.String()
}

// propLines renders one constructor parameter. Rules (same guarantees as iOS):
//   - lists: missing / not an array → empty; broken items dropped
//   - enums: unknown value → fallback entry; required ones default to it
//   - optional scalars / objects: wrong type → null instead of failing the parent
//   - required scalars / objects: missing or wrong → the parent is dropped
//     from its list (unless defaultOverrides gives a value)
func (g *generator) propLines(c *class, p *prop) []string {
	name := kotlinIdent(p.key)
	s := p.shape
	switch s.kind {
	case kList:
		return []string{
			"@Serializable(with = LossyListSerializer::class)",
			fmt.Sprintf("val %s: List<%s> = emptyList(),", name, g.elemType(s.elem)),
		}
	case kComponentType:
		return []string{fmt.Sprintf("val %s: ComponentType = ComponentType.%s,", name, "UNKNOWN")}
	case kEnum:
		e := s.enum
		if p.required {
			return []string{fmt.Sprintf("val %s: %s = %s.%s,", name, e.name, e.name, fallbackEntry(e))}
		}
		return []string{fmt.Sprintf("val %s: %s? = null,", name, e.name)}
	case kSealed:
		if p.required {
			return []string{fmt.Sprintf("val %s: %s,", name, s.class)}
		}
		return []string{fmt.Sprintf("val %s: %s? = null,", name, s.class)}
	case kClass, kComponent:
		t := s.class
		if s.kind == kComponent {
			t = componentName
		}
		if p.required && s.kind == kClass {
			return []string{fmt.Sprintf("val %s: %s,", name, t)}
		}
		g.lenient[t] = true
		return []string{
			fmt.Sprintf("@Serializable(with = %sLenientSerializer::class)", t),
			fmt.Sprintf("val %s: %s? = null,", name, t),
		}
	case kJSON:
		return []string{fmt.Sprintf("val %s: JsonElement? = null,", name)}
	case kJSONObject:
		return []string{
			"@Serializable(with = LenientJsonObjectSerializer::class)",
			fmt.Sprintf("val %s: JsonObject? = null,", name),
		}
	}
	t := scalarType(s.kind)
	if def, ok := defaultOverrides[c.name+"."+p.key]; ok {
		return []string{fmt.Sprintf("val %s: %s = %s,", name, t, def)}
	}
	if p.required {
		return []string{fmt.Sprintf("val %s: %s,", name, t)}
	}
	return []string{
		fmt.Sprintf("@Serializable(with = Lenient%sSerializer::class)", t),
		fmt.Sprintf("val %s: %s? = null,", name, t),
	}
}

func scalarType(k kind) string {
	switch k {
	case kInt:
		return "Int"
	case kNumber:
		return "Double"
	case kBool:
		return "Boolean"
	}
	return "String"
}

func (g *generator) elemType(s *shape) string {
	switch s.kind {
	case kList:
		return "List<" + g.elemType(s.elem) + ">"
	case kEnum:
		return s.enum.name
	case kClass, kSealed:
		return s.class
	case kComponent:
		return componentName
	case kComponentType:
		return "ComponentType"
	case kJSON:
		return "JsonElement"
	case kJSONObject:
		return "JsonObject"
	}
	return scalarType(s.kind)
}

func (g *generator) renderLenientObjects(component bool) string {
	var names []string
	for n := range g.lenient {
		if (n == componentName) == component {
			names = append(names, n)
		}
	}
	slices.Sort(names)
	var b strings.Builder
	for _, n := range names {
		fmt.Fprintf(&b, "\ninternal object %sLenientSerializer : LenientObjectSerializer<%s>(%s.serializer())\n", n, n, n)
	}
	return b.String()
}

// ---- component -------------------------------------------------------------

func (g *generator) renderComponent() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(imports(
		"kotlinx.serialization.ExperimentalSerializationApi",
		"kotlinx.serialization.KSerializer",
		"kotlinx.serialization.KeepGeneratedSerializer",
		"kotlinx.serialization.Serializable",
		"kotlinx.serialization.Transient",
		"kotlinx.serialization.encoding.Decoder",
		"kotlinx.serialization.encoding.Encoder",
		"kotlinx.serialization.json.JsonDecoder",
		"kotlinx.serialization.json.JsonElement",
		"kotlinx.serialization.json.JsonObject",
		"kotlinx.serialization.json.JsonPrimitive",
	))
	b.WriteString("\n/** 部品の種類(Container の enum と Leaf の const)。知らない値は [UNKNOWN]。 */\n")
	b.WriteString("@Serializable(with = ComponentTypeSerializer::class)\n")
	b.WriteString("enum class ComponentType(val wire: String, val isContainer: Boolean = false) {\n")
	for _, t := range g.compTypes {
		if t.container {
			fmt.Fprintf(&b, "    %s(%q, true),\n", screaming(t.wire), t.wire)
		} else {
			fmt.Fprintf(&b, "    %s(%q),\n", screaming(t.wire), t.wire)
		}
	}
	b.WriteString("\n    /** 知らない type(新しい版の部品)。描画器は「更新すると表示」の枠を出す(#351 §5)。 */\n")
	b.WriteString("    UNKNOWN(\"\"),\n}\n")
	b.WriteString(enumSerializer("ComponentType", "UNKNOWN"))
	b.WriteString("\n/** 部品 1 つ。全部品のキーを平らに持つ(#351 §7)。部品ごとに使えるキーは [DslKeys.component]。 */\n")
	b.WriteString(g.renderClass(g.byName[componentName],
		"@OptIn(ExperimentalSerializationApi::class)\n@KeepGeneratedSerializer\n@Serializable(with = ComponentSerializer::class)",
		[]string{
			"/** JSON の type の元の文字列。知らない type([ComponentType.UNKNOWN])でも残る(描画の木・「更新すると表示」に使う)。 */",
			"@Transient",
			`val rawType: String = "",`,
			"/** JSON の filter の元の値。配列(AND)でも残る(読み口は手書きの `Component.filters`)。 */",
			"@Transient",
			"val rawFilter: JsonElement? = null,",
		}))
	b.WriteString(componentSerializer)
	b.WriteString(g.renderLenientObjects(true))
	return b.String()
}

// ---- enums -----------------------------------------------------------------

func fallbackEntry(e *enumOcc) string {
	if v, ok := enumFallbacks[e.name]; ok {
		return screaming(v)
	}
	return unknownEntry(e)
}

func unknownEntry(e *enumOcc) string {
	for _, v := range e.values {
		if screaming(v) == "UNKNOWN" {
			return "UNRECOGNIZED"
		}
	}
	return "UNKNOWN"
}

func enumSerializer(name, fallback string) string {
	return fmt.Sprintf(`
internal object %sSerializer : LenientEnumSerializer<%s>(
    "%s.%s",
    %s.entries,
    %s::wire,
    %s.%s,
)
`, name, name, kotlinPackage, name, name, name, name, fallback)
}

func (g *generator) renderEnums() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(imports("kotlinx.serialization.Serializable"))
	for _, e := range g.enums {
		fmt.Fprintf(&b, "\n@Serializable(with = %sSerializer::class)\n", e.name)
		fmt.Fprintf(&b, "enum class %s(val wire: String) {\n", e.name)
		for _, v := range e.values {
			fmt.Fprintf(&b, "    %s(%q),\n", screaming(v), v)
		}
		fmt.Fprintf(&b, "\n    /** 知らない値(新しい版)。 */\n    %s(\"\"),\n}\n", unknownEntry(e))
		b.WriteString(enumSerializer(e.name, fallbackEntry(e)))
	}
	return b.String()
}

