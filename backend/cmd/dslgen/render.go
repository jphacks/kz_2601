func (g *generator) renderSealed() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString(imports(
		"kotlinx.serialization.KSerializer",
		"kotlinx.serialization.Serializable",
		"kotlinx.serialization.SerializationException",
		"kotlinx.serialization.descriptors.SerialDescriptor",
		"kotlinx.serialization.descriptors.buildClassSerialDescriptor",
		"kotlinx.serialization.encoding.Decoder",
		"kotlinx.serialization.encoding.Encoder",
		"kotlinx.serialization.json.Json",
		"kotlinx.serialization.json.JsonDecoder",
		"kotlinx.serialization.json.JsonElement",
		"kotlinx.serialization.json.JsonEncoder",
		"kotlinx.serialization.json.JsonObject",
		"kotlinx.serialization.json.JsonPrimitive",
		"kotlinx.serialization.json.booleanOrNull",
		"kotlinx.serialization.json.doubleOrNull",
		"kotlinx.serialization.json.longOrNull",
	))
	for _, sd := range g.sealed {
		g.renderOneSealed(&b, sd)
	}
	return b.String()
}

var primitiveOrder = []string{"string", "boolean", "integer", "number"}

func (g *generator) renderOneSealed(b *strings.Builder, sd *sealedDef) {
	n := sd.name
	fmt.Fprintf(b, "\n/** 型は %sRef などのオブジェクトか、そのままの値。どれにも合わない値は [%sUnknown]。 */\n", n, n)
	fmt.Fprintf(b, "@Serializable(with = %sSerializer::class)\nsealed interface %s\n", n, n)

	var prims []sealedVariant
	var objs []sealedVariant
	for _, v := range sd.variants {
		if v.primitive != "" {
			prims = append(prims, v)
		} else {
			objs = append(objs, v)
		}
	}
	slices.SortStableFunc(prims, func(a, c sealedVariant) int {
		return slices.Index(primitiveOrder, a.primitive) - slices.Index(primitiveOrder, c.primitive)
	})
	slices.SortStableFunc(objs, func(a, c sealedVariant) int { return len(c.required) - len(a.required) })

	b.WriteString("\n")
	for _, v := range prims {
		fmt.Fprintf(b, "data class %s(val value: %s) : %s\n", v.class, primitiveKotlin(v.primitive), n)
	}
	fmt.Fprintf(b, "\n/** どの形にも合わない値(新しい版の書き方など)。落とさずに持っておく。 */\ndata class %sUnknown(val raw: JsonElement) : %s\n", n, n)

	fmt.Fprintf(b, `
internal object %[1]sSerializer : KSerializer<%[1]s> {
    override val descriptor: SerialDescriptor = buildClassSerialDescriptor("%[2]s.%[1]s")

    override fun deserialize(decoder: Decoder): %[1]s {
        val input = decoder as? JsonDecoder ?: throw SerializationException("%[1]s は JSON からだけ読める")
        return decode%[1]s(input.json, input.decodeJsonElement())
    }

    override fun serialize(encoder: Encoder, value: %[1]s) {
        val output = encoder as? JsonEncoder ?: throw SerializationException("%[1]s は JSON にだけ書ける")
        val element: JsonElement = when (value) {
`, n, kotlinPackage)
	for _, v := range prims {
		fmt.Fprintf(b, "            is %s -> JsonPrimitive(value.value)\n", v.class)
	}
	for _, v := range objs {
		fmt.Fprintf(b, "            is %s -> output.json.encodeToJsonElement(%s.serializer(), value)\n", v.class, v.class)
	}
	fmt.Fprintf(b, "            is %sUnknown -> value.raw\n", n)
	b.WriteString("        }\n        output.encodeJsonElement(element)\n    }\n}\n")

	fmt.Fprintf(b, "\n/** オブジェクトは必須キーで形を見分ける(必須キーの多い形から)。 */\ninternal fun decode%[1]s(json: Json, element: JsonElement): %[1]s {\n", n)
	b.WriteString("    if (element is JsonPrimitive) {\n        return when {\n")
	for _, v := range prims {
		switch v.primitive {
		case "string":
			fmt.Fprintf(b, "            element.isString -> %s(element.content)\n", v.class)
		case "boolean":
			fmt.Fprintf(b, "            element.booleanOrNull != null -> %s(element.booleanOrNull!!)\n", v.class)
		case "integer":
			fmt.Fprintf(b, "            element.longOrNull != null -> %s(element.longOrNull!!)\n", v.class)
		case "number":
			fmt.Fprintf(b, "            element.doubleOrNull != null -> %s(element.doubleOrNull!!)\n", v.class)
		}
	}
	fmt.Fprintf(b, "            else -> %sUnknown(element)\n        }\n    }\n", n)
	fmt.Fprintf(b, "    if (element !is JsonObject) return %sUnknown(element)\n", n)
	fmt.Fprintf(b, "    val serializer: KSerializer<out %s> = when {\n", n)
	for _, v := range objs {
		fmt.Fprintf(b, "        element.keys.containsAll(%s) -> %s.serializer()\n", kotlinStringList("listOf", v.required), v.class)
	}
	fmt.Fprintf(b, "        else -> return %sUnknown(element)\n    }\n", n)
	fmt.Fprintf(b, "    return runCatching { json.decodeFromJsonElement(serializer, element) }.getOrElse { %sUnknown(element) }\n}\n", n)
}

func primitiveKotlin(t string) string {
	switch t {
	case "boolean":
		return "Boolean"
	case "integer":
		return "Long"
	case "number":
		return "Double"
	}
	return "String"
}

func kotlinStringList(fn string, vals []string) string {
	q := make([]string, len(vals))
	for i, v := range vals {
		q[i] = fmt.Sprintf("%q", v)
	}
	return fn + "(" + strings.Join(q, ", ") + ")"
}

// ---- key tables ------------------------------------------------------------

func (g *generator) renderKeys() string {
	var b strings.Builder
	b.WriteString(header)
	b.WriteString("\n/** 部品・アクションごとに書いてよいキー(スキーマの各定義と x-for から)。適合テストと検証に使う(#351 §7)。 */\nobject DslKeys {\n")
	b.WriteString("    val component: Map<ComponentType, Set<String>> = mapOf(\n")
	for _, t := range g.compTypes {
		fmt.Fprintf(&b, "        ComponentType.%s to %s,\n", screaming(t.wire), kotlinStringList("setOf", t.keys))
	}
	b.WriteString("    )\n")
	// Every other class whose `type` is an enum and whose keys carry x-for (Action).
	for _, c := range g.classes {
		def := g.defs.obj(c.name)
		if def == nil || c.name == componentName {
			continue
		}
		var typeEnum *enumOcc
		hasXFor := false
		props := def.obj("properties")
		for _, p := range c.props {
			if p.key == "type" && p.shape.kind == kEnum {
				typeEnum = p.shape.enum
			}
			if props.obj(p.key).has("x-for") {
				hasXFor = true
			}
		}
		if typeEnum == nil || !hasXFor {
			continue
		}
		field := strings.ToLower(c.name[:1]) + c.name[1:]
		fmt.Fprintf(&b, "\n    val %s: Map<%s, Set<String>> = mapOf(\n", field, typeEnum.name)
		for _, v := range typeEnum.values {
			keys := []string{}
			for _, k := range props.keys {
				if xf := props.obj(k).obj("x-for"); xf == nil || xf.has(v) {
					keys = append(keys, k)
				}
			}
			fmt.Fprintf(&b, "        %s.%s to %s,\n", typeEnum.name, screaming(v), kotlinStringList("setOf", keys))
		}
		b.WriteString("    )\n")
	}
	b.WriteString("}\n")
	return b.String()
}

// componentSerializer reads with the plugin serializer, then keeps the raw
// type string (iOS Component.rawType) and the raw filter (one object or an
// array; iOS Component.filters).
const componentSerializer = `
@OptIn(ExperimentalSerializationApi::class)
internal object ComponentSerializer : KSerializer<Component> {
    private val generated: KSerializer<Component> = Component.generatedSerializer()
    override val descriptor = generated.descriptor

    override fun deserialize(decoder: Decoder): Component {
        val input = decoder as? JsonDecoder ?: return generated.deserialize(decoder)
        val element = input.decodeJsonElement()
        val component = input.json.decodeFromJsonElement(generated, element)
        val obj = element as? JsonObject
        val raw = (obj?.get("type") as? JsonPrimitive)?.takeIf { it.isString }?.content
        return component.copy(rawType = raw ?: component.rawType, rawFilter = obj?.get("filter"))
    }

    override fun serialize(encoder: Encoder, value: Component) = generated.serialize(encoder, value)
}
`
